//! Тестирование основных методов, связанных с различными измерениями
//!
//! Данные тесты проверяют корректность работы с базовыми величинами, а именно:
//!  * проверку преобразований
//!  * проверку вычисления коэффициентов
//!  * проверку вычисления индекса в матрице (кадре) по положению (x, y)

use algorithms::processing::measures::*;
use algorithms::units::*;

/// Проверка перевода миллиметров в пиксели
///
/// Данный тест проверяет корректность перевода физического размера (в мм)
/// в количество пикселей с использованием различных коэффициентов `k`.
///
/// **Поля таблицы:**
/// - `mm` - количество миллиметров
/// - `k` - коэффициент перевода (px/mm)
/// - `expected_px` - ожидаемое количество пикселей
#[test]
fn test_convert_mm_to_px() {
    let cases = vec![
        // (mm, k, expected_px)
        (10, 2.0, 20),          // Целый коэффициент: 10 * 2 = 20
        (10, 1.5, 15),          // Дробный коэффициент: 10 * 1.5 = 15
        (10, 0.0, 0),           // Нулевой коэффициент: 10 * 0 = 0
        (10, 0.00000000001, 0), // Почти нулевой коэффициент: 10 * ~0 = 0
    ];

    for (mm, k, expected_px) in cases {
        let px = Millimeters::new(mm).as_pixels(k);
        assert_eq!(px, Pixels::new(expected_px), "Failed on {} mm with k={}", mm, k);
    }
}

/// Проверка перевода пикселей в байты
///
/// Данный тест проверяет вычисление объема памяти, занимаемого заданным
/// количеством пикселей при разной 'тяжести' одного пикселя (bpp).
///
/// **Поля таблицы:**
/// - `px` - количество пикселей
/// - `bytes_in_px` - количество байт на один пиксель
/// - `expected_bytes` - ожидаемый объем в байтах
#[test]
fn test_convert_px_to_bytes() {
    let cases = vec![
        // (px, bytes_in_px, expected_bytes)
        (10, 4, 40), // Обычный перевод: 10 * 4 = 40
        (10, 0, 0),  // Нулевой размер пикселя: 10 * 0 = 0
    ];

    for (px, bytes_in_px, expected_bytes) in cases {
        let bytes = Pixels::new(px).as_bytes(bytes_in_px);
        assert_eq!(
            bytes, expected_bytes,
            "Failed on {} px with {} bytes/px",
            px, bytes_in_px
        );
    }
}

/// Проверка вычисления коэффициента преобразования миллиметров в пиксели
///
/// Данный тест проверяет корректность расчета коэффициента `k` (px/mm)
/// при различных соотношениях длины.
///
/// **Поля таблицы:**
/// - `mm` - количество миллиметров
/// - `px` - количество пикселей
/// - `expected_k` - ожидаемое значение коэффициента
#[test]
fn test_calculate_mm_to_px_k() {
    let cases = vec![
        // (mm, px, expected_k)
        (10, 10, 1.0), // Одинаковые значения: 10 / 10 = 1
        (10, 20, 2.0), // Пикселей больше: 20 / 10 = 2
        (20, 10, 0.5), // Миллиметров больше: 10 / 20 = 0.5
    ];

    for (mm, px, expected_k) in cases {
        let k = calculate_mm_to_px_k(Millimeters::new(mm), Pixels::new(px));
        assert_eq!(k, expected_k, "Failed on mm={} px={}", mm, px);
    }
}

/// Проверка вычисления индекса начала пикселя (смещения в байтах)
///
/// Данный тест проверяет вычисление смещения первого байта по координатам `x`
/// и `y` для буфера изображения.
///
/// **Поля таблицы:**
/// - `x` - положение пикселя по горизонтали (столбец)
/// - `y` - положение пикселя по вертикали (строка)
/// - `px_in_row` - ширина кадра (строки) в пикселях
/// - `bytes_in_px` - количество байт на один пиксель
/// - `expected_index` - ожидаемый индекс первого байта
#[test]
fn test_calculate_px_x_y_to_bytes() {
    let cases = vec![
        // (x, y, px_in_row, bytes_in_px, expected_index)
        (0, 0, 10, 4, 0),  // Нулевая позиция: 0*4 + 0*4*10 = 0
        (9, 0, 10, 4, 36), // Конец строки: 9*4 + 0*4*10 = 36
        (0, 1, 10, 4, 40), // Начало второй строки: 0*4 + 1*4*10 = 40
        (1, 0, 10, 4, 4),  // Сдвиг X на 1: +1 пиксель (+4 байта) от нуля
        (0, 2, 10, 4, 80), // Сдвиг Y на 2: +2 строки (+80 байт) от нуля
    ];

    for (x, y, px_in_row, bytes_in_px, expected_index) in cases {
        let i = calculate_px_x_y_to_bytes(
            Pixels::new(x),
            Pixels::new(y),
            Pixels::new(px_in_row),
            bytes_in_px,
        );
        assert_eq!(
            i, expected_index,
            "Failed on x={} y={} px_in_row={} bytes_in_px={}",
            x, y, px_in_row, bytes_in_px
        );
    }
}
