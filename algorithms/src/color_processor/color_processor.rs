//! Алгоритм обработки массива цвета 

pub fn alg(data: &[u8], width: u32, height: u32) {
    // Проверка на пустой массив (на всякий случай)
    if data.is_empty() {
        return;
    }

    // В Rust данные в слайсе уже можно читать через обычные индексы
    // data[0] - это Blue (или Red, в зависимости от формата)
    if data.len() >= 3 {
        println!("R: {}, G: {}, B: {}", data[2], data[1], data[0]);
    }
}